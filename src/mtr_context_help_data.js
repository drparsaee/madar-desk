export const MADAR_HELP_CATEGORIES = Object.freeze([
  'کارها','کارت و پروژه','پیداکردن','برنامه‌ریزی','همکاری و اتصال','مدیریت و تنظیمات'
]);

const byId = new Map(MADAR_HELP_SECTIONS.map(section=>[section.id,section]));
const aliases = Object.freeze({
  'timeline':'time', 'time-dashboard':'time', 'kanban':'board', 'tasks':'board',
  'card':'cards', 'task':'cards', 'task-editor':'cards',
  'reports':'reporting', 'rules':'automation', 'automation-rules':'automation',
  'trello-import':'import', 'portable-export':'export', 'calendar-interop':'calendar',
  'taraz':'taraz-exchange','tarazExchange':'taraz-exchange',
  'lan-connection':'lan','users':'lan-users','notification':'notifications',
  'workspaces':'workspace','board-archive':'archive','card-trash':'trash'
});

export function resolveMadarHelpSection(section) {
  const key = typeof section === 'string' ? section.trim() : '';
  return byId.get(key) || byId.get(aliases[key]) || byId.get('board');
}

export function filterMadarHelpSections({query='',category='',availableSections}={}) {
  const normalized = String(query ?? '').trim().toLocaleLowerCase('fa');
  const allowed = Array.isArray(availableSections)
    ? new Set(availableSections.map(id=>byId.get(id)?.id || aliases[id]).filter(Boolean))
    : null;
  return MADAR_HELP_SECTIONS.filter(item=>{
    if (allowed && !allowed.has(item.id)) return false;
    if (category && item.category !== category) return false;
    if (!normalized) return true;
    return [item.id,item.title,item.category,...item.steps]
      .join(' ').toLocaleLowerCase('fa').includes(normalized);
  });
}
